#!/usr/bin/env python3
"""Portable local renderer; copied into each project's .agent-config directory."""

import argparse
import hashlib
import json
from pathlib import Path
import sys

HEADER = "<!-- Generated by AgentConfig. Edit shared sources or PROJECT_RULES.md, then regenerate. -->\n"
LEGACY = "<!-- Generated by scripts/install-agent-rules.py from PROJECT_RULES.md. Do not edit. -->\n\n"
MANIFEST = ".agent-config/manifest.json"


def digest(data):
    return hashlib.sha256(data).hexdigest()


def json_bytes(value):
    return (json.dumps(value, indent=2, ensure_ascii=False) + "\n").encode()


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def safe_path(root, relative):
    rel = Path(relative)
    if rel.is_absolute() or ".." in rel.parts:
        raise ValueError("Unsafe managed path: " + str(relative))
    path = root / rel
    # Never write through a symlink, including a directory symlink.
    for part in (path, *path.parents):
        if part == root:
            break
        if part.is_symlink():
            raise ValueError("Refusing symlink: " + str(part))
    if not path.resolve().is_relative_to(root.resolve()):
        raise ValueError("Managed path escapes project: " + str(relative))
    return path


def load_config(root):
    config = read_json(root / "agent-config.json")
    if config.get("schema") != 1:
        raise ValueError("Unsupported agent-config.json schema")
    for field in ("profiles", "skills"):
        names = config.get(field)
        if not isinstance(names, list) or any(
                not isinstance(n, str) or not n or
                any(c not in "abcdefghijklmnopqrstuvwxyz0123456789-" for c in n)
                for n in names) or len(set(names)) != len(names):
            raise ValueError("Invalid or duplicate names in " + field)
    if "general" not in config["profiles"]:
        raise ValueError("Every project must select the general profile")
    if not isinstance(config.get("source"), str) or not config["source"]:
        raise ValueError("Missing AgentConfig source reference")
    return config


def instruction_outputs(root, config, snapshot):
    if snapshot.get("schema") != 1 or snapshot.get("profiles") != config["profiles"] \
            or snapshot.get("skills") != config["skills"]:
        raise ValueError("Profile/skill selection changed; sync from AgentConfig first")
    rules = snapshot["rules"]
    fingerprint = digest(json_bytes(rules))
    text = HEADER + (
        "\n# Project instructions\n\n"
        "Shared source: AgentConfig (`agent-config.json` records its local path).\n"
        "Profiles: " + ", ".join(config["profiles"]) + ".\n"
        "Shared rules SHA-256: `" + fingerprint + "`.\n\n"
        "These instructions include a portable snapshot of the shared rules.\n"
        "Project-specific additions below refine shared defaults within their scope.\n"
        "Regenerate locally with `python3 .agent-config/render.py`; refresh shared\n"
        "rules and skills with the central `scripts/sync.py`.\n\n"
    )
    text += "\n\n".join(rule["content"].strip() for rule in rules)
    local = root / "PROJECT_RULES.md"
    if local.exists():
        text += "\n\n---\n\n" + local.read_text(encoding="utf-8").strip()
    return {name: (text + "\n").encode() for name in ("AGENTS.md", "CLAUDE.md")}


def plan(root, outputs, *, complete=True, adopt_legacy=False):
    """Preflight ownership before writing anything; preserve manual edits."""
    root = root.resolve()
    manifest_path = safe_path(root, MANIFEST)
    old = read_json(manifest_path) if manifest_path.exists() else {"schema": 1, "files": {}}
    if old.get("schema") != 1 or not isinstance(old.get("files"), dict):
        raise ValueError("Invalid managed-file manifest")
    owned = old["files"]
    for name, expected in owned.items():
        path = safe_path(root, name)
        if not complete and name not in outputs and not path.exists():
            raise ValueError("Missing managed file; sync from AgentConfig: " + str(path))
        if path.exists() and digest(path.read_bytes()) != expected:
            raise ValueError("Modified generated file; preserve edits before syncing: " + str(path))
    for name, data in outputs.items():
        path = safe_path(root, name)
        if path.exists() and name not in owned:
            legacy = adopt_legacy and name in ("AGENTS.md", "CLAUDE.md") \
                and path.read_bytes().startswith(LEGACY.encode())
            if not legacy:
                raise ValueError("Refusing unmanaged file: " + str(path))
    updated = {} if complete else dict(owned)
    updated.update({name: digest(data) for name, data in outputs.items()})
    writes = dict(outputs)
    writes[MANIFEST] = json_bytes({"schema": 1, "files": dict(sorted(updated.items()))})
    writes = {name: data for name, data in writes.items()
              if not safe_path(root, name).exists() or safe_path(root, name).read_bytes() != data}
    deletes = [name for name in owned if complete and name not in outputs
               and safe_path(root, name).exists()]
    return root, writes, deletes


def apply(plans, *, check=False):
    changed = False
    for root, writes, deletes in plans:
        for name in writes:
            print(("STALE " if check else "WRITE ") + str(root / name))
            changed = True
        for name in deletes:
            print(("STALE " if check else "REMOVE ") + str(root / name))
            changed = True
        if not check:
            for name, data in writes.items():
                path = safe_path(root, name)
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
            for name in deletes:
                safe_path(root, name).unlink()
    if not changed:
        print("Agent instructions and managed files are up to date.")
    return 1 if check and changed else 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--project", type=Path, default=Path(__file__).resolve().parent.parent)
    args = parser.parse_args(argv)
    try:
        root = args.project.resolve()
        config = load_config(root)
        snapshot = read_json(root / ".agent-config/shared.json")
        outputs = instruction_outputs(root, config, snapshot)
        return apply([plan(root, outputs, complete=False)], check=args.check)
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(str(error), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
